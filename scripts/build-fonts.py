"""Builds the Bereg DS font files from the Fontsource packages (devDependencies).

- IBM Plex Sans (variable): wght axis limited to 300-700, hinting removed.
- IBM Plex Mono 400: hinting removed.
- Subsets: latin, latin-ext (₪, names like Łukasz), cyrillic (Russian, Ukrainian). Same unicode-range as Fontsource.
  Greek, Vietnamese and Cyrillic Extended are left out: other characters fall back to the system font.
- One woff2 file per subset.

Writes src/fonts/*.woff2, src/fonts/OFL.txt and src/css/fonts.css.
The results are committed, so `npm run build` (and Cloudflare, and npm publish) need no Python.
Run again only when the fonts change: `npm run build:fonts` (needs Python 3 with `pip install fonttools brotli`).
"""
import re
import shutil
from pathlib import Path

from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
SANS = ROOT / 'node_modules/@fontsource-variable/ibm-plex-sans'
MONO = ROOT / 'node_modules/@fontsource/ibm-plex-mono'
OUT = ROOT / 'src/fonts'
CSS = ROOT / 'src/css/fonts.css'
WGHT = (300, 700)
SUBSETS = ('latin', 'latin-ext', 'cyrillic')


def faces(css_path):
    """(subset name, source file, unicode-range) for each @font-face in a Fontsource CSS file, in its order."""
    text = css_path.read_text()
    out = []
    for block in re.findall(r'@font-face\s*{([^}]*)}', text):
        src = re.search(r'url\(\./files/([^)]+\.woff2)\)', block).group(1)
        subset_name = re.search(r'/\* ibm-plex-(?:sans|mono)-(.+?)-(?:wght|400)-normal \*/', '/* ' + src.replace('.woff2', '') + ' */').group(1)
        if subset_name not in SUBSETS:
            continue
        urange = re.search(r'unicode-range:\s*([^;]+);', block).group(1).strip()
        out.append((src, urange))
    return out


def unhint(font):
    """Remove TrueType hinting (same as fontTools.subset with hinting=False), keep all glyphs and features."""
    for tag in ('fpgm', 'prep', 'cvt ', 'cvar', 'hdmx', 'LTSH', 'VDMX'):
        if tag in font:
            del font[tag]
    glyf = font['glyf']
    for name in font.getGlyphOrder():
        glyf[name].removeHinting()
    maxp = font['maxp']
    for attr in ('maxZones', 'maxTwilightPoints', 'maxStorage', 'maxFunctionDefs',
                 'maxInstructionDefs', 'maxStackElements', 'maxSizeOfInstructions'):
        setattr(maxp, attr, 1 if attr == 'maxZones' else 0)
    # Glyphs with no hints render with the rasterizer's own smoothing; gasp: smooth at all sizes.
    if 'gasp' in font:
        font['gasp'].gaspRange = {0xFFFF: 0x000F}


def build(src_dir, src_name, dest_name, wght=None):
    font = TTFont(src_dir / 'files' / src_name)
    if wght:
        font = instancer.instantiateVariableFont(font, {'wght': wght}, updateFontNames=False)
    unhint(font)
    font.flavor = 'woff2'
    dest = OUT / dest_name
    font.save(dest)
    return (src_dir / 'files' / src_name).stat().st_size, dest.stat().st_size


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)
    rules, sizes = [], []

    for src, urange in faces(SANS / 'wght.css'):
        name = src.replace('ibm-plex-sans-', 'plex-sans-').replace('-wght-normal', '-wght')
        before, after = build(SANS, src, name, WGHT)
        sizes.append((name, before, after))
        rules.append(
            "@font-face { font-family: 'IBM Plex Sans Variable'; font-style: normal; font-weight: 300 700; font-display: swap;\n"
            f"  src: url('../fonts/{name}') format('woff2');\n  unicode-range: {urange}; }}"
        )

    for src, urange in faces(MONO / '400.css'):
        name = src.replace('ibm-plex-mono-', 'plex-mono-').replace('-400-normal', '-400')
        before, after = build(MONO, src, name)
        sizes.append((name, before, after))
        rules.append(
            "@font-face { font-family: 'IBM Plex Mono'; font-style: normal; font-weight: 400; font-display: swap;\n"
            f"  src: url('../fonts/{name}') format('woff2');\n  unicode-range: {urange}; }}"
        )

    shutil.copy(SANS / 'LICENSE', OUT / 'OFL.txt')

    header = """/* Bereg DS fonts: IBM Plex Sans (variable, weights 300-700) and IBM Plex Mono 400. Generated by scripts/build-fonts.py, do not edit by hand.
   Self-hosted woff2 files in ../fonts (built from Fontsource, hinting removed, Sans weight axis limited to 300-700). License: ../fonts/OFL.txt.
   Subsets: latin, latin-ext, cyrillic, each with its own unicode-range, so the browser loads only the scripts a page uses.
   Other scripts (Greek, Vietnamese...) fall back to the system font.
   For Hebrew use IBM Plex Sans Hebrew (@fontsource/ibm-plex-sans-hebrew) and add it to --font in your project. */
"""
    fallbacks = """
/* Metric-matched fallbacks: system fonts scaled to Plex's size and line box, so the font swap does not shift layout.
   Variable names in tokens.css (--font, --mono) list these right after Plex. */
@font-face { font-family: 'IBM Plex Sans Fallback'; font-weight: 100 500; src: local('Arial'); size-adjust: 100.8%; ascent-override: 101.7%; descent-override: 27.3%; line-gap-override: 0%; }
@font-face { font-family: 'IBM Plex Sans Fallback'; font-weight: 600 900; src: local('Arial Bold'), local('Arial-BoldMT'); size-adjust: 98.7%; ascent-override: 103.8%; descent-override: 27.9%; line-gap-override: 0%; }
@font-face { font-family: 'IBM Plex Mono Fallback'; src: local('Courier New'); size-adjust: 100%; ascent-override: 102.5%; descent-override: 27.5%; line-gap-override: 0%; }
"""
    CSS.write_text(header + '\n' + '\n'.join(rules) + '\n' + fallbacks)

    for name, before, after in sizes:
        print(f'{name}: {before / 1000:.1f} -> {after / 1000:.1f} kB')


if __name__ == '__main__':
    main()
